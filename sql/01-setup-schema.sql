-- Setup schema dashboard izin pramuka
-- Jalankan di Supabase SQL Editor

create table if not exists kelas (
  id bigint generated always as identity primary key,
  nama text unique not null
);

create table if not exists siswa (
  id bigint generated always as identity primary key,
  nis text unique not null,
  nama text not null,
  jk text,
  agama text,
  kelas_id bigint references kelas(id) on delete cascade
);

create table if not exists pendamping (
  id bigint generated always as identity primary key,
  nama text not null,
  kontak text,
  aktif boolean default true,
  kelas_id bigint references kelas(id) on delete cascade
);

create table if not exists izin (
  id uuid default gen_random_uuid() primary key,
  siswa_id bigint references siswa(id) on delete cascade not null,
  tanggal date not null default current_date,
  jenis text not null default 'izin' check (jenis in ('izin','sakit','alpa')),
  keterangan text,
  status text not null default 'menunggu' check (status in ('menunggu','disetujui','ditolak')),
  created_at timestamptz default now()
);

